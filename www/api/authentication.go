var (
	hashKey       []byte
	blockKey      []byte
	CookieEncoder *securecookie.SecureCookie
)

const COOKIENAME = "quotient"

// cookieSecure returns whether cookies should use the Secure flag (HTTPS only)
func (a *API) cookieSecure() bool {
	// If OIDC is enabled and using HTTPS callback, enforce secure cookies
	if a.conf.OIDCSettings.OIDCEnabled && strings.HasPrefix(a.conf.OIDCSettings.OIDCRedirectURL, "https://") {
		return true
	}
	// Otherwise, use secure cookies only if SSL is configured
	return a.conf.SslSettings != (config.SslConfig{})
}

func init() {
	if _, err := os.Stat("config/COOKIEKEY"); err != nil {
		// Ensure config directory exists
		if err := os.MkdirAll("config", 0750); err != nil { // #nosec G301 -- config dir needs group read for deployment
			log.Fatalln(err)
		}
		w, err := os.Create("config/COOKIEKEY")
		if err != nil {
			log.Fatalln(err)
		}
		// nolint:errcheck
		defer w.Close()

		hashKey = securecookie.GenerateRandomKey(64)
		blockKey = securecookie.GenerateRandomKey(32)
		_, _ = fmt.Fprintln(w, "# AUTOMATICALLY GENERATED BY INIT DO NOT TOUCH")
		_, _ = fmt.Fprintf(w, "hashKey=%s\n", base64.StdEncoding.EncodeToString(hashKey))
		_, _ = fmt.Fprintf(w, "blockKey=%s\n", base64.StdEncoding.EncodeToString(blockKey))
	} else {
		f, err := os.Open("config/COOKIEKEY")
		if err != nil {
			log.Fatalln(err)
		}
		// nolint:errcheck
		defer f.Close()

		scanner := bufio.NewScanner(f)
		for scanner.Scan() {
			line := scanner.Text()
			if strings.Contains(line, "hashKey=") {
				decoded, err := base64.StdEncoding.DecodeString(strings.ReplaceAll(line, "hashKey=", ""))
				if err != nil {
					log.Fatalln(err)
				}
				hashKey = decoded
			} else if strings.Contains(line, "blockKey=") {
				decoded, err := base64.StdEncoding.DecodeString(strings.ReplaceAll(line, "blockKey=", ""))
				if err != nil {
					log.Fatalln(err)
				}
				blockKey = decoded
			}
		}
	}
	CookieEncoder = securecookie.New(hashKey, blockKey)
}

func (a *API) Login(w http.ResponseWriter, r *http.Request) {
	type Form struct {
		Username string `json:"username"`
		Password string `json:"password"`
	}

	var form Form

	decoder := json.NewDecoder(r.Body)
	err := decoder.Decode(&form)
	if err != nil {
		WriteJSON(w, http.StatusBadRequest, map[string]any{"error": "Invalid request body"})
		slog.Error(err.Error())
		return
	}

	// check credentials
	auth, err := a.auth(form.Username, form.Password)
	if err != nil {
		WriteJSON(w, http.StatusUnauthorized, map[string]any{"error": "Incorrect username/password"})
		slog.Info("Failed logon", "username", form.Username)
		return
	}

	cookie, err := CookieEncoder.Encode(COOKIENAME, auth)
	if err != nil {
		WriteJSON(w, http.StatusInternalServerError, map[string]any{"error": "Authentication error"})
		slog.Error(err.Error())
		return
	}

	http.SetCookie(w, &http.Cookie{
		Name:     COOKIENAME,
		Value:    cookie,
		MaxAge:   int((time.Hour * 24).Seconds()),
		HttpOnly: true,
		Secure:   a.cookieSecure(),
		SameSite: http.SameSiteLaxMode,
		Path:     "/",
	})

	slog.Info("Successful login", "username", form.Username)
}

func (a *API) Logout(w http.ResponseWriter, r *http.Request) {
	http.SetCookie(w, &http.Cookie{
		Name:     COOKIENAME,
		Value:    "",
		MaxAge:   -1,
		HttpOnly: true,
		Secure:   a.cookieSecure(),
		SameSite: http.SameSiteLaxMode,
		Path:     "/",
	})
	id, _ := IdentityFrom(r.Context())
	slog.Info("Successful logout", "username", id.Username)
}

// Authenticate resolves the caller from their session cookie. Reports false
// when the request carries no usable session, or when the identity cannot be
// resolved, in which case it also clears the cookie. Refreshes the cookie on
// success.
func (a *API) Authenticate(w http.ResponseWriter, r *http.Request) (Identity, bool) {
	token, err := r.Cookie(COOKIENAME)
	if err != nil {
		if err != http.ErrNoCookie {
			slog.Error(err.Error())
		}
		return Identity{}, false
	}

	var value map[string]any
	if err := CookieEncoder.Decode(COOKIENAME, token.Value, &value); err != nil {
		slog.Error(err.Error())
		return Identity{}, false
	}

	username, ok := value["username"].(string)
	if !ok || username == "" {
		slog.Error("session cookie carries no username")
		return Identity{}, false
	}

	// Extract auth source (default to "local" for backward compatibility)
	authSource := "local"
	if source, ok := value["authSource"].(string); ok {
		authSource = source
	}

	// Local sessions carry a fingerprint of the account's passwords. Cookies
	// issued before it existed have none and are rejected.
	credential, _ := value["credential"].(string)

	id, err := a.resolveIdentity(username, authSource, credential)
	if err != nil {
		slog.Error(err.Error())
		http.SetCookie(w, &http.Cookie{
			Name:     COOKIENAME,
			Value:    "",
			MaxAge:   -1,
			HttpOnly: true,
			Secure:   a.cookieSecure(),
			SameSite: http.SameSiteLaxMode,
			Path:     "/",
		})
		return Identity{}, false
	}

	// cookie refresh while still have value
	http.SetCookie(w, &http.Cookie{
		Name:     COOKIENAME,
		Value:    token.Value,
		MaxAge:   int((time.Hour * 24).Seconds()),
		HttpOnly: true,
		Secure:   a.cookieSecure(),
		SameSite: http.SameSiteLaxMode,
		Path:     "/",
	})

	return id, true
}

func (a *API) auth(username string, password string) (map[string]any, error) {
	if a.localPasswordMatches(username, password) {
		return map[string]any{"username": username, "authSource": "local", "credential": a.localCredential(username)}, nil
	}

	// auth from other sources
	// if ldap configs are present, try to auth against ldap
	if a.conf.LdapSettings != (config.LdapAuthConfig{}) {
		groups, err := ldapdir.Authenticate(a.conf.LdapSettings, username, password)
		if err != nil {
			return nil, err
		}
		if len(a.ldapGroupRoles(groups)) == 0 {
			return nil, errors.New("LDAP user has no authorized roles")
		}
		return map[string]any{"username": username, "authSource": "ldap"}, nil
	}

	return nil, errors.New("no auth source matched credentials")
}

// localPasswordMatches reports whether password is the configured password of
// a local account named username, in any role.
func (a *API) localPasswordMatches(username, password string) bool {
	for _, admin := range a.conf.Admin {
		if username == admin.Name && password == admin.Pw {
			return true
		}
	}
	for _, team := range a.conf.Team {
		if username == team.Name && password == team.Pw {
			return true
		}
	}
	for _, red := range a.conf.Red {
		if username == red.Name && password == red.Pw {
			return true
		}
	}
	for _, inject := range a.conf.Inject {
		if username == inject.Name && password == inject.Pw {
			return true
		}
	}
	return false
}

// localCredential fingerprints every password configured for the local account
// username. Login stores it in the session cookie and resolveIdentity compares
// it on every request, so changing any of the account's passwords ends the
// sessions issued before the change. It is an HMAC keyed with the cookie hash
// key, so the cookie never carries the password or a plain hash of it.
func (a *API) localCredential(username string) string {
	mac := hmac.New(sha256.New, hashKey)
	_, _ = fmt.Fprintf(mac, "local-session\x00%d:%s", len(username), username)
	add := func(role, name, pw string) {
		if name == username {
			_, _ = fmt.Fprintf(mac, "\x00%s\x00%d:%s", role, len(pw), pw)
		}
	}
	for _, admin := range a.conf.Admin {
		add("admin", admin.Name, admin.Pw)
	}
	for _, red := range a.conf.Red {
		add("red", red.Name, red.Pw)
	}
	for _, team := range a.conf.Team {
		add("team", team.Name, team.Pw)
	}
	for _, inject := range a.conf.Inject {
		add("inject", inject.Name, inject.Pw)
	}
	return base64.RawStdEncoding.EncodeToString(mac.Sum(nil)[:16])
}
